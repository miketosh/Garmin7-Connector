
"""Embed the public xDrip G7 KEKS setup-QR identity into a build.

The decoded certificate/key bytes are written only to generated Monkey C
source in the build workspace. Never print the raw values or commit generated
source. The upstream QR is publicly available, but its third field is a private
signing key used by the protocol; the compiled PRG necessarily embeds this
material. Anyone distributing a PRG must understand that consequence and check
the upstream project's terms/permission. The consistency checks do not prove
that a sensor still accepts this identity.
"""
from __future__ import annotations

import sys
import io
from contextlib import redirect_stdout
from pathlib import Path

from inspect_g7_keks_qr import (
    OFFICIAL_QR_URL,
    InspectError,
    decode_image,
    decode_xml_or_text,
    decode_xdp2,
    inspect_parts,
    read_source,
)

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "source" / "KeksQrMaterial.mc"
ORDER = ("keks_p1", "keks_p2", "keks_p3")


def load_official_parts():
    image_bytes, decoded_text = read_source(OFFICIAL_QR_URL)
    if decoded_text is None:
        decoded_text = decode_image(image_bytes or b"")
    if decoded_text.startswith("xdp2:"):
        parts = decode_xdp2(decoded_text)
    else:
        parts = decode_xml_or_text(decoded_text)
    if set(parts) != set(ORDER) or any(not parts[name] for name in ORDER):
        raise InspectError("Official QR did not contain all three non-empty KEKS parts.")
    return parts


def _monkeyc_byte_array(value: bytes) -> str:
    if not value:
        raise ValueError("A KEKS part is empty.")



    tokens = [f"0x{byte:02X}" for byte in value]
    lines = ["        " + ", ".join(tokens[i:i + 16]) for i in range(0, len(tokens), 16)]
    return "[\n" + ",\n".join(lines) + "\n    ]b"


def render_source(parts):
    if set(parts) != set(ORDER):
        raise ValueError("Expected exactly keks_p1, keks_p2, and keks_p3.")
    if any(not parts[name] for name in ORDER):
        raise ValueError("A KEKS part is empty.")
    names = ("partA", "partB", "partC")
    functions = []
    for name, function_name in zip(ORDER, names):
        functions.append(
            f"    static function {function_name}() {{ return {_monkeyc_byte_array(parts[name])}; }}"
        )
    return (
        "// GENERATED by tools/embed_g7_keks_qr.py during CI. DO NOT COMMIT REAL VALUES.\n"
        "// Values come from the official public xDrip G7 setup QR.\n"
        "// The runtime receives binary byte arrays; no on-watch hex conversion is needed.\n"
        "class ScoutKeksQrMaterial {\n"
        + "\n".join(functions) + "\n"
        "}\n"
    )


def main():
    try:
        parts = load_official_parts()


        # Validate the certificate/key relationships quietly in CI. The
        # certificate's X.509 validity date is known/expected and is not a
        # useful build warning; keep the full report available in the manual
        # inspector tool, but do not repeat it during every build.
        with redirect_stdout(io.StringIO()):
            inspection_result = inspect_parts(parts)
        if inspection_result != 0:
            raise InspectError("Official QR certificate/key consistency validation failed.")
        generated = render_source(parts)
        OUTPUT.write_text(generated, encoding="utf-8")
        print(
            "Embedded official xDrip G7 KEKS setup identity into the CI build "
            f"(A={len(parts['keks_p1'])} bytes, B={len(parts['keks_p2'])} bytes, "
            f"C={len(parts['keks_p3'])} bytes; raw values suppressed)."
        )
        return 0
    except Exception as exc:
        print(f"ERROR: could not embed official G7 KEKS setup identity: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
