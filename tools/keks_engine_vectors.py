"""Generate synthetic KEKS session vectors for the Monkey C engine tests.

Writes test/KeksEngineVectors.mc. Both sides use fixed, made-up scalars and
the synthetic pairing code 2468; nothing here is sensor, QR, or user data.
The watch-side test (test/KeksEngineTest.mc) runs the real engine tasks on
these inputs in the Connect IQ simulator and compares every output byte.
"""
from __future__ import annotations

import hashlib
import random
from pathlib import Path

from keks_p256_reference import G, N, point_add, scalar_multiply
from keks_protocol_reference import (
    PARTY_CLIENT, PARTY_SERVER, derive_shared_key, ecdsa_sign_with_nonce,
    make_zkp_packet, password_integer, serialize_packet, verify_zkp,
)

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "test" / "KeksEngineVectors.mc"
PASSWORD = "2468"


def scalar(rng: random.Random) -> int:

    return rng.randrange(2, N - 2)


def build_session(seed: int) -> dict:
    rng = random.Random(seed)
    x1, x2, v1, v2, v3 = (scalar(rng) for _ in range(5))
    b1, b2, w1, w2, w3 = (scalar(rng) for _ in range(5))
    pw = password_integer(PASSWORD)

    c1 = make_zkp_packet(G, x1, v1, PARTY_CLIENT)
    c2 = make_zkp_packet(G, x2, v2, PARTY_CLIENT)
    s1 = make_zkp_packet(G, b1, w1, PARTY_SERVER)
    s2 = make_zkp_packet(G, b2, w2, PARTY_SERVER)

    gen_client = point_add(point_add(c1[1], s1[1]), s2[1])
    c3 = make_zkp_packet(gen_client, (x2 * pw) % N, v3, PARTY_CLIENT)
    gen_server = point_add(point_add(s1[1], c1[1]), c2[1])
    s3 = make_zkp_packet(gen_server, (b2 * pw) % N, w3, PARTY_SERVER)

    assert verify_zkp(G, s1[1], s1[2], s1[0], PARTY_SERVER)
    assert verify_zkp(G, s2[1], s2[2], s2[0], PARTY_SERVER)
    verify_client = point_add(point_add(c1[1], c2[1]), s1[1])
    assert verify_zkp(verify_client, s3[1], s3[2], s3[0], PARTY_SERVER)

    key = derive_shared_key(x2, PASSWORD, s2, s3)
    assert key == derive_shared_key(b2, PASSWORD, c2, c3)
    return {
        "x1": x1, "x2": x2, "v1": v1, "v2": v2, "v3": v3,
        "c1": serialize_packet(*c1), "c2": serialize_packet(*c2), "c3": serialize_packet(*c3),
        "s1": serialize_packet(*s1), "s2": serialize_packet(*s2), "s3": serialize_packet(*s3),
        "key": key, "b2": b2, "w3": w3,
    }


def hex32(value: int) -> str:
    return value.to_bytes(32, "big").hex().upper()


def render() -> str:
    session = build_session(20261023)
    sig_d, sig_k = 0x1F2E3D4C5B6A79881726354453627180A9B8C7D6E5F40312233445566778899A, 0x0A0B0C0D0E0F101112131415161718191A1B1C1D1E1F2021222324252627282
    message = bytes(range(16))
    signature = ecdsa_sign_with_nonce(sig_d, sig_k, message)
    small_signature = ecdsa_sign_with_nonce(5, 7, message)
    lines = [
        "// GENERATED by tools/keks_engine_vectors.py. Synthetic values only:",
        "// fixed made-up scalars and test pairing code " + PASSWORD + ".",
        "(:test)",
        "class KeksEngineVectors {",
        f'    static const PASSWORD = "{PASSWORD}";',
    ]
    for name in ("x1", "x2", "v1", "v2", "v3", "b2", "w3"):
        lines.append(f'    static const {name.upper()} = "{hex32(session[name])}";')
    for name in ("c1", "c2", "c3", "s1", "s2", "s3"):
        lines.append(f'    static const {name.upper()} = "{session[name].hex().upper()}";')
    lines.append(f'    static const KEY = "{session["key"].hex().upper()}";')
    lines.append(f'    static const SIG_D = "{hex32(sig_d)}";')
    lines.append(f'    static const SIG_K = "{hex32(sig_k)}";')
    lines.append(f'    static const SIG = "{signature.hex().upper()}";')
    lines.append(f'    static const SIG_SMALL = "{small_signature.hex().upper()}";')
    lines.append(f'    static const MESSAGE = "{message.hex().upper()}";')
    lines.append("}")
    return "\n".join(lines) + "\n"


def main() -> int:
    OUTPUT.parent.mkdir(exist_ok=True)
    OUTPUT.write_text(render(), encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)} ({hashlib.sha256(OUTPUT.read_bytes()).hexdigest()[:12]})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
